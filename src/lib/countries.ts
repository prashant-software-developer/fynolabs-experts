/** The list for the country picker: the matching dictionary's names plus every other country. */
export const COUNTRY_OPTIONS: string[] = [...new Set([...COUNTRIES.map((c) => c.name), ...ALL])].sort((a, b) => a.localeCompare(b));

const BY_LOWER = new Map(COUNTRY_OPTIONS.map((c) => [c.toLowerCase(), c]));

/** "usa" -> "United States", "côte d'ivoire" -> "Côte d'Ivoire"; unknown -> null. */
export function toCountryName(raw: string | null | undefined): string | null {
  if (!raw || !raw.trim()) return null;
  const known = lookupCountry(raw);
  if (known) return known;
  return BY_LOWER.get(raw.trim().toLowerCase()) ?? null;
}
